# Modules
# Definition: A module is a file containing Python definitions and statements. The file name is the module name with the suffix .py appended.

# Steps to create a Module:
# 1) Create a new python file.
# 2) Write your code in that file.
# 3) Save it as sampleModule.py
# 4) Import this file into another python program using import statement.
# 5) Use functions defined inside the imported module by calling them using dot operator.


# Steps to use a Module:
# 1) Open a new python file.
# 2) Import the required module using import statement.
# 3) Call the function defined inside the imported module using dot operator.
# 4) Run the program.



# Steps to Create a Package
# 1) Create a folder.
# 2) Inside the folder create __init__.py file.
# 3) Add all the modules you want to include in package inside the folder.
# 4) Now you can import any of these modules from outside the package using import statement.
# 5) Run the program.


